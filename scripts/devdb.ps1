<#
.SYNOPSIS
    Local PostgreSQL for LifeOS development: no Windows service, no admin rights.

.DESCRIPTION
    Uses the PostgreSQL binaries installed on this machine, keeps the database
    cluster in %LOCALAPPDATA%\LifeOS\pgdata and stores generated passwords in
    backend\.env (git-ignored).

        powershell -ExecutionPolicy Bypass -File .\scripts\devdb.ps1 init     # first run
        powershell -ExecutionPolicy Bypass -File .\scripts\devdb.ps1 start    # after a reboot
        powershell -ExecutionPolicy Bypass -File .\scripts\devdb.ps1 stop
        powershell -ExecutionPolicy Bypass -File .\scripts\devdb.ps1 status

    The cluster is created with locale C and the builtin collation provider
    (C.UTF-8). The stock Windows installer runs initdb with the system locale
    (for example Russian_Russia.1251) and fails with
    "invalid byte sequence for encoding UTF8".
#>
param(
    [Parameter(Position = 0)]
    [ValidateSet('init', 'start', 'stop', 'status')]
    [string]$Command = 'status'
)

$ErrorActionPreference = 'Stop'

$RepoRoot = Split-Path -Parent $PSScriptRoot
$EnvFile = Join-Path $RepoRoot 'backend\.env'
$PgBin = if ($env:PG_BIN) { $env:PG_BIN } else { 'C:\Program Files\PostgreSQL\18\bin' }
$BaseDir = Join-Path $env:LOCALAPPDATA 'LifeOS'
$DataDir = Join-Path $BaseDir 'pgdata'
$LogFile = Join-Path $BaseDir 'postgres.log'
$Port = 5432

function Get-PgExe([string]$Name) {
    $path = Join-Path $PgBin "$Name.exe"
    if (-not (Test-Path -LiteralPath $path)) {
        throw "Cannot find $path. Set PG_BIN to the PostgreSQL bin directory."
    }
    return $path
}

function New-Secret([int]$Bytes = 24) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return ([Convert]::ToBase64String($buffer)).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function Read-EnvFile {
    $map = @{}
    if (Test-Path -LiteralPath $EnvFile) {
        foreach ($line in Get-Content -LiteralPath $EnvFile) {
            if ($line -match '^\s*([A-Z0-9_]+)\s*=\s*(.*)$') { $map[$Matches[1]] = $Matches[2].Trim() }
        }
    }
    return $map
}

function Initialize-EnvFile {
    $map = Read-EnvFile
    if ($map.ContainsKey('POSTGRES_SUPERUSER_PASSWORD') -and $map.ContainsKey('LIFEOS_DB_PASSWORD')) {
        if (-not $map.ContainsKey('DEV_DATABASE_URL')) {
            # Older .env files predate the separate development database.
            Add-Content -LiteralPath $EnvFile -Encoding ASCII `
                -Value "DEV_DATABASE_URL=postgresql+asyncpg://lifeos:$($map['LIFEOS_DB_PASSWORD'])@localhost:$Port/lifeos_dev"
            $map = Read-EnvFile
        }
        return $map
    }
    if (Test-Path -LiteralPath $EnvFile) {
        throw "$EnvFile exists but has no database passwords. Remove it or add POSTGRES_SUPERUSER_PASSWORD and LIFEOS_DB_PASSWORD."
    }
    $superuser = New-Secret
    $app = New-Secret
    $jwt = New-Secret 48
    $lines = @(
        '# Local development settings generated by scripts/devdb.ps1. Never commit this file.',
        "POSTGRES_SUPERUSER_PASSWORD=$superuser",
        "LIFEOS_DB_PASSWORD=$app",
        "DATABASE_URL=postgresql+asyncpg://lifeos:$app@localhost:$Port/lifeos",
        "DEV_DATABASE_URL=postgresql+asyncpg://lifeos:$app@localhost:$Port/lifeos_dev",
        "TEST_DATABASE_URL=postgresql+asyncpg://lifeos:$app@localhost:$Port/lifeos_test",
        "JWT_SECRET=$jwt"
    )
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $EnvFile) | Out-Null
    Set-Content -LiteralPath $EnvFile -Value $lines -Encoding ASCII
    Write-Host "Created $EnvFile with new random passwords."
    return Read-EnvFile
}

function Test-ServerRunning {
    if (-not (Test-Path -LiteralPath (Join-Path $DataDir 'PG_VERSION'))) { return $false }
    $null = & (Get-PgExe 'pg_ctl') status -D $DataDir
    return ($LASTEXITCODE -eq 0)
}

function Initialize-Cluster($Map) {
    if (Test-Path -LiteralPath (Join-Path $DataDir 'PG_VERSION')) {
        Write-Host "Cluster already exists: $DataDir"
        return
    }
    New-Item -ItemType Directory -Force -Path $BaseDir | Out-Null
    $pwFile = Join-Path $BaseDir 'initdb-pw.tmp'
    try {
        Set-Content -LiteralPath $pwFile -Value $Map['POSTGRES_SUPERUSER_PASSWORD'] -Encoding ASCII -NoNewline
        & (Get-PgExe 'initdb') -D $DataDir -U postgres "--pwfile=$pwFile" --auth=scram-sha-256 `
            --encoding=UTF8 --locale=C --locale-provider=builtin --builtin-locale=C.UTF-8
        if ($LASTEXITCODE -ne 0) { throw "initdb failed with exit code $LASTEXITCODE" }
    }
    finally {
        Remove-Item -LiteralPath $pwFile -Force -ErrorAction SilentlyContinue
    }
}

function Start-Server {
    if (-not (Test-Path -LiteralPath (Join-Path $DataDir 'PG_VERSION'))) {
        throw "No database cluster in $DataDir yet. Create it once with: powershell -ExecutionPolicy Bypass -File .\scripts\devdb.ps1 init"
    }
    if (Test-ServerRunning) {
        Write-Host "PostgreSQL is already running on localhost:$Port"
        return
    }
    & (Get-PgExe 'pg_ctl') start -D $DataDir -l $LogFile -w -o "-p $Port"
    if ($LASTEXITCODE -ne 0) { throw "pg_ctl start failed with exit code $LASTEXITCODE. See $LogFile" }
}

function Initialize-Databases($Map) {
    $sqlFile = Join-Path $BaseDir 'bootstrap.sql'
    $sql = @'
\getenv app_password LIFEOS_DB_PASSWORD
SELECT format('CREATE ROLE lifeos LOGIN PASSWORD %L', :'app_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'lifeos') \gexec
ALTER ROLE lifeos WITH LOGIN PASSWORD :'app_password';
SELECT 'CREATE DATABASE lifeos OWNER lifeos'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'lifeos') \gexec
SELECT 'CREATE DATABASE lifeos_dev OWNER lifeos'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'lifeos_dev') \gexec
SELECT 'CREATE DATABASE lifeos_test OWNER lifeos'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'lifeos_test') \gexec
'@
    $env:PGPASSWORD = $Map['POSTGRES_SUPERUSER_PASSWORD']
    $env:LIFEOS_DB_PASSWORD = $Map['LIFEOS_DB_PASSWORD']
    try {
        Set-Content -LiteralPath $sqlFile -Value $sql -Encoding ASCII
        & (Get-PgExe 'psql') -h localhost -p $Port -U postgres -d postgres -v ON_ERROR_STOP=1 -q -f $sqlFile
        if ($LASTEXITCODE -ne 0) { throw "psql failed with exit code $LASTEXITCODE" }
    }
    finally {
        Remove-Item Env:\PGPASSWORD -ErrorAction SilentlyContinue
        Remove-Item Env:\LIFEOS_DB_PASSWORD -ErrorAction SilentlyContinue
        Remove-Item -LiteralPath $sqlFile -Force -ErrorAction SilentlyContinue
    }
}

switch ($Command) {
    'init' {
        $map = Initialize-EnvFile
        Initialize-Cluster $map
        Start-Server
        Initialize-Databases $map
        Write-Host "Ready: databases 'lifeos' (your data), 'lifeos_dev' and 'lifeos_test' on localhost:$Port (role 'lifeos')."
    }
    'start' { Start-Server }
    'stop' {
        if (Test-ServerRunning) { & (Get-PgExe 'pg_ctl') stop -D $DataDir -m fast }
        else { Write-Host 'PostgreSQL is not running.' }
    }
    'status' {
        if (Test-ServerRunning) { Write-Host "PostgreSQL is running on localhost:$Port (data: $DataDir)" }
        else { Write-Host 'PostgreSQL is not running. Start it with: powershell -ExecutionPolicy Bypass -File .\scripts\devdb.ps1 start' }
    }
}
